#!/usr/bin/env python3
"""Check every locked npm licence and preserve notices from the installed tree.
Run after npm ci in contracts, server and frame. No network requests.
"""
import json
import re
from pathlib import Path
from collections import Counter

ROOT = Path(__file__).resolve().parent.parent
FRAME = ROOT / 'frame-web'
APPROVED = {'MIT', 'ISC', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause',
            'BlueOak-1.0.0', 'MIT-0', 'Python-2.0', 'CC-BY-4.0', 'CC0-1.0',
            '0BSD', 'MPL-2.0'}
locks = [(ROOT / component, json.loads((ROOT / component / 'package-lock.json').read_text())) for component in ['contracts', 'server', 'frame-web']]
mit = (ROOT / 'LICENSE').read_text().split('Permission is hereby granted', 1)[1]
mit = 'Permission is hereby granted' + mit
inventory = []
notices = [
    'HomeControl third-party notices\nGenerated by scripts/audit-licenses.py.\n'
    'Versions, SPDX licences, and source archives for ALL locked packages are in\n'
    'third-party/dependencies.json. Platform-specific optional packages are fetched\n'
    'by npm on the target platform; their parent project notices also apply.\n'
    'This source distribution does not include node_modules or third-party binaries.\n',
    'Lucide icons (including the rendered native PNGs):\n' +
    (FRAME / 'node_modules/lucide-react/LICENSE').read_text(),
    'Feather-derived Lucide icons:\n' + (ROOT / 'third-party/upstream/feather.txt').read_text(),
]
parents = {
    '@esbuild/': 'esbuild', '@rollup/rollup-': 'rollup',
    '@resvg/resvg-js-': '@resvg/resvg-js', '@humanfs/types': '@humanfs/core',
}
# These packages declare a licence but publish no separate licence file.
# Attribution comes from their published README/package.json; the permission
# text is the unmodified standard MIT grant, not a claim of an upstream file.
mit_authors = {
    'abstract-logging': 'James Sumners', 'keyv': 'Jared Wray',
    'natural-compare': '2012-2015 Lauri Rooden', 'stackback': 'Roman Shtylman',
}
def licence_files(folder):
    return [p for p in folder.iterdir() if p.is_file() and
            re.match(r'^(licen[cs]e|copying|notice)([.\-]|$)', p.name, re.I)]

notices.append('Tailwind CSS 3.4.17 palette swatches [MIT]\nUpstream: https://github.com/tailwindlabs/tailwindcss/tree/v3.4.17\n\n' + (ROOT / 'third-party/upstream/tailwindcss.txt').read_text())

included_notices = set()
for component, lock in locks:
    for path, data in sorted(lock['packages'].items()):
        if 'node_modules/' not in path or data.get('link'):
            continue
        name = path.rsplit('node_modules/', 1)[-1]
        licence = data.get('license')
        if licence not in APPROVED:
            raise SystemExit(f'Review required: {name}@{data["version"]}: {licence}')
        inventory.append({'component': component.name, 'name': name, 'version': data['version'], 'license': licence,
                          'developmentOnly': data.get('dev', False),
                          'optional': data.get('optional', False),
                          'sourceArchive': data.get('resolved'), 'integrity': data.get('integrity')})
        key = (name, data['version'])
        if key in included_notices: continue
        folder = component / path
        if not (folder / 'package.json').exists():
            continue
        files = licence_files(folder)
        source = 'Published licence files'
        if not files:
            for prefix, parent in parents.items():
                if name.startswith(prefix):
                    files = licence_files(component / 'node_modules' / parent)
                    source = f'Parent package licence: {parent}'
                    break
        if files:
            text = '\n\n'.join(p.read_text(errors='replace') for p in sorted(files))
        elif name == 'esrecurse':
            text = (folder / 'esrecurse.js').read_text().split('*/', 1)[0].removeprefix('/*')
            source = 'Published source header'
        elif name == 'imurmurhash':
            text = (folder / 'README.md').read_text().split('License (MIT)', 1)[1]
            source = 'Published README licence section'
        elif name == 'saxes':
            text = (ROOT / 'third-party/upstream/saxes.txt').read_text()
            source = 'Upstream: https://github.com/lddubeau/saxes/blob/master/LICENSE'
        elif name in mit_authors:
            text = f'MIT License\n\nCopyright (c) {mit_authors[name]}\n\n{mit}'
            source = 'Published package MIT declaration and attribution; standard MIT text'
        else:
            raise SystemExit(f'No licence notice found: {name}')
        included_notices.add(key)
        notices.append(f'{name}@{data["version"]} [{licence}]\n{source}\n\n{text.strip()}\n')


(ROOT / 'third-party/dependencies.json').write_text(json.dumps(inventory, indent=2) + '\n')
notice_text = ('\n' + '=' * 78 + '\n\n').join(notices)
(ROOT / 'THIRD-PARTY-NOTICES.txt').write_text('\n'.join(line.rstrip() for line in notice_text.splitlines()) + '\n')
(FRAME / 'public/licenses.txt').write_text((ROOT / 'LICENSE').read_text() + '\n\n' + (ROOT / 'THIRD-PARTY-NOTICES.txt').read_text())
counts = Counter(i['license'] for i in inventory)
unique = len({(i['name'], i['version']) for i in inventory})
print(f'Checked {len(inventory)} lockfile entries ({unique} unique dependency versions): no missing or unreviewed licences.')
print(', '.join(f'{name}: {count}' for name, count in sorted(counts.items())))
